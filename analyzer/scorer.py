def score_text(title: str, summary: str = "") -> dict:
    """对文本进行利好/利空评分

    Returns:
        dict: {
            "bullish_pct": int,   # 0-100
            "bearish_pct": int,   # 0-100
            "sentiment": str,     # "bullish" / "bearish" / "neutral"
            "keywords_matched": list[str],
        }
    """
    text = (title + " " + summary).lower()

    bullish_weight = 0
    bearish_weight = 0
    matched_keywords = []

    for keyword, weight in BULLISH_KEYWORDS:
        if keyword.lower() in text:
            bullish_weight += weight
            matched_keywords.append(keyword)

    for keyword, weight in BEARISH_KEYWORDS:
        if keyword.lower() in text:
            bearish_weight += weight
            matched_keywords.append(keyword)

    if bullish_weight == 0 and bearish_weight == 0:
        return {
            "bullish_pct": 50,
            "bearish_pct": 50,
            "sentiment": "neutral",
            "keywords_matched": [],
        }

    total = bullish_weight + bearish_weight
    bullish_pct = round((bullish_weight / total) * 100)
    bearish_pct = 100 - bullish_pct

    if bullish_pct >= 65:
        sentiment = "bullish"
    elif bearish_pct >= 65:
        sentiment = "bearish"
    else:
        sentiment = "neutral"

    return {
        "bullish_pct": bullish_pct,
        "bearish_pct": bearish_pct,
        "sentiment": sentiment,
        "keywords_matched": matched_keywords,
    }
